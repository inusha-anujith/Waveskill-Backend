(async () => {
    try {
        await mongoose.connect(process.env.MONGO_URI);

        // One-time migration for accounts created before `status` existed.
        // This has to be a raw updateMany: loading such a document through the
        // model applies the schema default in memory, so a doc.status check
        // always looks populated and would never write the field to disk.
        const migrated = await User.collection.updateMany(
            { status: { $exists: false } },
            { $set: { status: 'Active' } }
        );
        if (migrated.modifiedCount) {
            console.log(`Backfilled status='Active' on ${migrated.modifiedCount} pre-existing account(s)`);
        }

        let created = 0;
        let backfilled = 0;
        let unchanged = 0;

        for (const u of DEMO_USERS) {
            const existing = await User.findOne({ email: u.email });

            if (!existing) {
                const user = await User.create(u);
                // Only employees/managers get a demo CV, matching cvUpdateStatus.
                if (u.cvUpdateStatus !== 'Needs Update') {
                    user.cvFile = writePlaceholderCV(user);
                    await user.save();
                }
                created++;
                continue;
            }

            // The original seeder skipped anyone who already existed, which left
            // previously-seeded accounts without a marital status forever. Fill
            // in the new fields on existing records instead of skipping them.
            let changed = false;

            if (!existing.maritalStatus) {
                existing.maritalStatus = u.maritalStatus;
                changed = true;
            }
            if (u.cvUpdateStatus !== 'Needs Update' && !existing.cvFile) {
                existing.cvFile = writePlaceholderCV(existing);
                existing.cvUpdateStatus = u.cvUpdateStatus;
                changed = true;
            }
            if (changed) {
                await existing.save();
                backfilled++;
            } else {
                unchanged++;
            }
        }

        console.log(`Users seeded: ${created} created, ${backfilled} backfilled, ${unchanged} already up to date`);
        console.log('Default password for demo employees: Demo@1234');
        console.log('Manager password: Manager@123');
        process.exit(0);
    } catch (e) {
        console.error(`Seed users failed: ${e.message}`);
        process.exit(1);
    }
})();
