// Builds a minimal but genuinely valid one-page PDF so the Admin "View CV"
// feature has a real file to open. Offsets are computed as the body is
// assembled, because a PDF xref table must point at exact byte positions.
const buildPlaceholderCV = (name, position) => {
    const text = (s) => s.replace(/([\\()])/g, '\\$1');
    const content =
        `BT /F1 22 Tf 72 760 Td (${text(name)}) Tj ET\n` +
        `BT /F1 13 Tf 72 735 Td (${text(position || 'Waveskill Employee')}) Tj ET\n` +
        `BT /F1 11 Tf 72 700 Td (Placeholder CV generated by scripts/seedUsers.js) Tj ET\n` +
        `BT /F1 11 Tf 72 682 Td (Replace it by uploading a real CV from the Employee profile page.) Tj ET\n`;

    const objects = [
        '<</Type/Catalog/Pages 2 0 R>>',
        '<</Type/Pages/Kids[3 0 R]/Count 1>>',
        '<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 842]/Resources<</Font<</F1 4 0 R>>>>/Contents 5 0 R>>',
        '<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>',
        `<</Length ${content.length}>>\nstream\n${content}endstream`
    ];

    let pdf = '%PDF-1.4\n';
    const offsets = [];
    objects.forEach((body, i) => {
        offsets.push(pdf.length);
        pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
    });

    const xrefStart = pdf.length;
    pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
    offsets.forEach((off) => {
        pdf += `${String(off).padStart(10, '0')} 00000 n \n`;
    });
    pdf += `trailer\n<</Size ${objects.length + 1}/Root 1 0 R>>\nstartxref\n${xrefStart}\n%%EOF\n`;

    return Buffer.from(pdf, 'latin1');
};

// Writes the placeholder CV to the same folder real uploads land in, and
// returns the stored filename (matching what uploadCV persists).
const writePlaceholderCV = (user) => {
    const filename = `seed-cv-${user.email.split('@')[0]}.pdf`;
    fs.mkdirSync(CV_UPLOAD_DIR, { recursive: true });
    fs.writeFileSync(path.join(CV_UPLOAD_DIR, filename), buildPlaceholderCV(user.name, user.position));
    return filename;
};

